class CommonNeighborAnalyzer:
    """
    Analyzes common neighbors to suggest proof approaches.
    
    For two theorems A and B that share neighbors N1, N2, ... Nk:
    - What structure do they share?
    - What proof techniques apply?
    - What universal properties might be relevant?
    """
    
    def __init__(self, kernel: MathKernel):
        self.kernel = kernel
        self.category = kernel.leandojo
        
        # Build neighbor graph
        self.neighbors = defaultdict(set)
        for mor in self.category.morphisms():
            self.neighbors[mor.source].add(mor.target)
            self.neighbors[mor.target].add(mor.source)
        
        self.objects = {obj.name: obj for obj in self.category.objects()}
    
    def find_common_neighbors(self, thm_a: str, thm_b: str) -> List[str]:
        """Find all common neighbors of two theorems."""
        neighbors_a = self.neighbors.get(thm_a, set())
        neighbors_b = self.neighbors.get(thm_b, set())
        return list(neighbors_a & neighbors_b)
    
    def analyze_shared_structure(self, common_neighbors: List[str]) -> Dict:
        """
        Analyze what structure the common neighbors share.
        """
        if not common_neighbors:
            return {'pattern': 'no_common_neighbors'}
        
        # Analyze fields
        fields = defaultdict(int)
        types = defaultdict(int)
        
        for neighbor in common_neighbors:
            obj = self.objects.get(neighbor)
            if obj:
                fields[obj.metadata.get('field', 'unknown')] += 1
                types[obj.type_name] += 1
        
        # Find dominant patterns
        dominant_field = max(fields.keys(), key=lambda k: fields[k]) if fields else 'unknown'
        dominant_type = max(types.keys(), key=lambda k: types[k]) if types else 'unknown'
        
        # Determine proof approach based on patterns
        proof_approaches = self._suggest_proof_approach(dominant_field, dominant_type, fields, types)
        
        return {
            'common_count': len(common_neighbors),
            'dominant_field': dominant_field,
            'dominant_type': dominant_type,
            'field_distribution': dict(fields),
            'type_distribution': dict(types),
            'proof_approaches': proof_approaches,
            'pattern': self._classify_pattern(fields, types),
        }
    
    def _suggest_proof_approach(self, field: str, type_name: str, 
                                fields: Dict, types: Dict) -> List[str]:
        """Suggest proof approaches based on field and type patterns."""
        approaches = []
        
        # Field-specific suggestions
        field_approaches = {
            'categorytheory': [
                'Use universal property (initial/terminal object)',
                'Apply adjunction if available',
                'Check if Yoneda lemma applies',
                'Consider natural transformation',
                'Use functoriality',
            ],
            'topology': [
                'Use continuity arguments',
                'Apply compactness if relevant',
                'Check separation axioms',
                'Consider homeomorphism',
                'Use connectedness arguments',
            ],
            'algebra': [
                'Use homomorphism properties',
                'Apply isomorphism theorems',
                'Check group/ring axioms',
                'Consider quotient structures',
            ],
            'numbertheory': [
                'Use divisibility arguments',
                'Apply modular arithmetic',
                'Consider prime factorization',
                'Use induction',
            ],
            'analysis': [
                'Use epsilon-delta arguments',
                'Apply convergence theorems',
                'Check continuity/differentiability',
                'Use completeness',
            ],
            'homologicalcomplex': [
                'Use exact sequence properties',
                'Apply snake lemma',
                'Consider connecting homomorphism',
                'Use homology functor',
            ],
        }
        
        approaches.extend(field_approaches.get(field, field_approaches.get('algebra', []))[:3])
        
        # Type-specific suggestions
        if type_name == 'Theorem':
            approaches.append('Construct explicit proof term')
        elif type_name == 'Definition':
            approaches.append('Unfold definitions and simplify')
        
        return approaches
    
    def _classify_pattern(self, fields: Dict, types: Dict) -> str:
        """Classify the pattern of common neighbors."""
        if len(fields) == 1:
            return 'single_field_cluster'
        elif len(fields) <= 3:
            return 'multi_field_bridge'
        else:
            return 'cross_domain_junction'
    
    def analyze_pair(self, thm_a: str, thm_b: str) -> Dict:
        """Full analysis of a theorem pair."""
        common = self.find_common_neighbors(thm_a, thm_b)
        structure = self.analyze_shared_structure(common)
        structure['common_neighbors'] = common[:10]  # List first 10
        structure['source'] = thm_a
        structure['target'] = thm_b
        return structure



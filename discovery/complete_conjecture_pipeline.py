    try:
        with open('hole_navigation_results.json', 'r') as f:
            nav_results = json.load(f)
        conjectures = [r.get('conjecture') for r in nav_results.get('results', []) if r.get('conjecture')]
        print(f"      Found {len(conjectures)} conjectures to formalize")
    except FileNotFoundError:
        print("      ERROR: hole_navigation_results.json not found")
        conjectures = []
    
    # PART 1: Lean Formalization
    print("\n[3/5] Generating Lean formalizations...")
    formalizer = LeanFormalizer(kernel)
    
    lean_files = []
    for i, conj in enumerate(conjectures[:5]):  # Top 5
        lean_code = formalizer.formalize_conjecture(conj)
        filename = f"conjectures/conjecture_{i+1}.lean"
        lean_files.append({
            'filename': filename,
            'conjecture': conj.get('conjecture_name', f'conjecture_{i+1}'),
        })
    
    # Create conjectures directory and save files
    import os
    os.makedirs('conjectures', exist_ok=True)
    
    for lf in lean_files:
        filepath = lf['filename']
        # Generate code for this conjecture
        idx = lean_files.index(lf)
        if idx < len(conjectures):
            code = formalizer.formalize_conjecture(conjectures[idx])
            with open(filepath, 'w', encoding='utf-8') as f:
                f.write(code)
            print(f"      Generated: {filepath}")
    
    # PART 2: Common Neighbor Analysis
    print("\n[4/5] Analyzing common neighbors for proof approaches...")
    analyzer = CommonNeighborAnalyzer(kernel)
    
    proof_analyses = []
    for i, conj in enumerate(conjectures[:5]):
        related = conj.get('related_theorems', [])
        if len(related) >= 2:
            analysis = analyzer.analyze_pair(related[0], related[1])
            analysis['conjecture_name'] = conj.get('conjecture_name', f'conjecture_{i+1}')
            proof_analyses.append(analysis)
            
            print(f"\n      {conj.get('conjecture_name', 'Unknown')}:")

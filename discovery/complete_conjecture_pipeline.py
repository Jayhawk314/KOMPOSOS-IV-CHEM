@dataclass
class BridgeScore:
    """Score for a bridge edge."""
    source: str
    target: str
    consequence_score: float  # How many theorems depend on this
    cross_domain_score: float  # Does it cross field boundaries?
    age_gap_score: float  # Historical gap between theorems
    difficulty_score: float  # How hard are the connected theorems?
    total_score: float
    
    def to_dict(self):
        return {
            'source': self.source,
            'target': self.target,
            'scores': {
                'consequence': self.consequence_score,
                'cross_domain': self.cross_domain_score,
                'age_gap': self.age_gap_score,
                'difficulty': self.difficulty_score,
            },
            'total_score': self.total_score,
        }

class BridgeRanker:
    """
    Ranks all bridge edges by consequence.
    
    Scoring formula:
    bridge_score = cross_domain_weight × fan_out × age_gap_penalty
    
    High-scoring bridges are the most valuable knowledge transfer points.
    """
    
    def __init__(self, kernel: MathKernel):
        self.kernel = kernel
        self.category = kernel.leandojo
        self.objects = {obj.name: obj for obj in self.category.objects()}
        
        # Build graph
        self.outgoing = defaultdict(set)
        self.incoming = defaultdict(set)
        
        for mor in self.category.morphisms():
            self.outgoing[mor.source].add(mor.target)
            self.incoming[mor.target].add(mor.source)
    
    def compute_fan_out(self, theorem: str) -> int:
        """Count how many theorems depend on this one."""
        return len(self.incoming.get(theorem, set()))
    
    def is_cross_domain(self, thm_a: str, thm_b: str) -> bool:
        """Check if two theorems are in different fields."""
        obj_a = self.objects.get(thm_a)
        obj_b = self.objects.get(thm_b)
        
        if not obj_a or not obj_b:
            return False
        
        field_a = obj_a.metadata.get('field', 'unknown')
        field_b = obj_b.metadata.get('field', 'unknown')
        
        return field_a != field_b
    
    def score_bridge(self, source: str, target: str) -> BridgeScore:
        """Compute consequence score for a bridge."""
        # Consequence: fan-out (how many depend on this)
        fan_out = self.compute_fan_out(target)
        consequence_score = min(1.0, fan_out / 100.0)  # Normalize
        
        # Cross-domain bonus
        cross_domain = self.is_cross_domain(source, target)
        cross_domain_score = 1.0 if cross_domain else 0.3
        
        # Age gap (simplified - would need timestamp data)
        age_gap_score = 0.5  # Default
        
        # Difficulty (based on proof complexity if available)
        source_obj = self.objects.get(source)
        difficulty = source_obj.metadata.get('difficulty', 0.5) if source_obj else 0.5
        difficulty_score = difficulty
        
        # Total score (weighted combination)
        total = (
            0.3 * consequence_score +
            0.35 * cross_domain_score +
            0.15 * age_gap_score +
            0.2 * difficulty_score
        )
        
        return BridgeScore(
            source=source,
            target=target,
            consequence_score=consequence_score,
            cross_domain_score=cross_domain_score,
            age_gap_score=age_gap_score,
            difficulty_score=difficulty_score,
            total_score=total,
        )
    
    def rank_all_bridges(self, sample_size: int = 10000) -> List[BridgeScore]:
        """
        Rank all bridge edges.
        
        For speed, sample from the graph rather than scoring all 645K edges.
        """
        import random
        
        # Get all edges
        edges = [(s, t) for s, targets in self.outgoing.items() for t in targets]
        
        # Sample
        if len(edges) > sample_size:
            edges = random.sample(edges, sample_size)
        
        print(f"      Scoring {len(edges)} bridge edges...")
        
        # Score each edge
        scores = []
        for i, (source, target) in enumerate(edges):
            score = self.score_bridge(source, target)
            scores.append(score)
            
            if (i + 1) % 2000 == 0:
                print(f"        Scored {i+1}/{len(edges)} edges...")
        
        # Sort by total score
        scores.sort(key=lambda x: x.total_score, reverse=True)
        
        return scores



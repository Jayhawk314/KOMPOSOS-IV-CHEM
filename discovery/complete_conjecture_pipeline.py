    print("\n[5/5] Ranking bridge edges by consequence...")
    ranker = BridgeRanker(kernel)
    
    print("      Computing bridge scores (sample of 10K edges)...")
    bridge_scores = ranker.rank_all_bridges(sample_size=10000)
    
    print(f"\n      TOP 20 BRIDGES (by consequence score):")
    print("      " + "-" * 70)
    print(f"      {'Rank':<5} {'Score':<8} {'Cross-Domain':<12} {'Bridge'}")
    print("      " + "-" * 70)
    
    top_bridges = []
    for i, score in enumerate(bridge_scores[:20]):
        cross = "Yes" if score.cross_domain_score > 0.5 else "No"
        bridge_str = f"{score.source[:30]} → {score.target[:25]}"
        print(f"      {i+1:<5} {score.total_score:.4f}   {cross:<12} {bridge_str}")
        top_bridges.append(score.to_dict())
    
    # Save all results
    print("\n" + "=" * 70)
    print("  SAVING RESULTS")
    print("=" * 70)
    
    results = {
        'lean_formalizations': lean_files,
        'proof_analyses': proof_analyses,
        'top_bridges': top_bridges,
        'bridge_statistics': {
            'total_scored': len(bridge_scores),
            'cross_domain_count': sum(1 for s in bridge_scores if s.cross_domain_score > 0.5),
            'avg_score': sum(s.total_score for s in bridge_scores) / len(bridge_scores) if bridge_scores else 0,
        },
    }
    
    with open('complete_conjecture_pipeline.json', 'w') as f:
        json.dump(results, f, indent=2)
    
    print(f"\n  Results saved to: complete_conjecture_pipeline.json")
    print(f"  Lean files saved to: conjectures/")
    
    # Final summary
    print("\n" + "=" * 70)
    print("  PIPELINE COMPLETE")
    print("=" * 70)
    
